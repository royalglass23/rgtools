import { act, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
const mocks = vi.hoisted(() => ({ auth: vi.fn(), range: vi.fn(), fetch: vi.fn(), identity: vi.fn(), refresh: vi.fn() }))
vi.mock('@/lib/dashboard-access', () => ({ requireDashboardUser: mocks.auth }))
vi.mock('../published-source', () => ({ readPublishedRange: mocks.range, publishedSourceConfigured: () => true, getReceiptReadMessage: () => undefined }))
vi.mock('../keyless-google-auth', () => ({ verifyPublishedSourceIdentity: mocks.identity }))
vi.mock('next/navigation', () => ({ useRouter: () => ({ refresh: mocks.refresh }) }))
import { PublishedRefreshControl } from '../PublishedRefreshControl'

const headers = ['requestId', 'status', 'outputVersion', 'completedAt']
const requestId = () => JSON.parse(mocks.fetch.mock.calls[0][1].body).requestId as string
const receipt = (status: 'success' | 'no_change' | 'failed') => [headers, [requestId(), status, 'fictional-v2', '2026-11-19T01:00:00Z']]
beforeEach(() => {
  vi.resetAllMocks(); vi.useFakeTimers(); vi.stubGlobal('fetch', mocks.fetch)
  vi.stubEnv('KANBAN_BOT_WEBHOOK_URL', 'https://bot.example.test/refresh')
  vi.stubEnv('KANBAN_BOT_WEBHOOK_SECRET', 'fictional-secret')
  vi.stubEnv('KANBAN_BOT_RECEIPTS_RANGE', "'RGTools Refresh'!A:D")
  mocks.auth.mockResolvedValue({ id: 'fictional-staff' })
  mocks.fetch.mockResolvedValue(new Response('', { status: 200 }))
  mocks.range.mockResolvedValue([headers])
})
afterEach(() => { vi.useRealTimers(); vi.unstubAllEnvs(); vi.unstubAllGlobals() })

describe('published refresh control with its actual server actions', () => {
  it('does not trigger on mount; one click waits for completion and guards in-flight clicks', async () => {
    render(<PublishedRefreshControl />)
    expect(mocks.fetch).not.toHaveBeenCalled()
    const button = screen.getByRole('button', { name: 'Refresh' })
    await act(async () => { fireEvent.click(button); fireEvent.click(button) })
    expect(mocks.fetch).toHaveBeenCalledOnce()
    expect(button).toBeDisabled()
    expect(mocks.refresh).not.toHaveBeenCalled()
    await act(async () => { await vi.advanceTimersByTimeAsync(10_000) })
    expect(screen.getByRole('status')).toHaveTextContent('Current published rows remain visible')
    expect(mocks.refresh).not.toHaveBeenCalled()
    mocks.range.mockResolvedValue(receipt('no_change'))
    await act(async () => { await vi.advanceTimersByTimeAsync(10_000) })
    expect(mocks.refresh).toHaveBeenCalledOnce()
    expect(screen.getByRole('status')).toHaveTextContent('no changes')
    expect(button).not.toBeDisabled()
  })
  it('preserves the current view on explicit failure and never automatically retriggers', async () => {
    render(<PublishedRefreshControl />)
    await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Refresh' })) })
    mocks.range.mockResolvedValue(receipt('failed'))
    await act(async () => { await vi.advanceTimersByTimeAsync(30_000) })
    expect(screen.getByRole('status')).toHaveTextContent('Kanban reported that this refresh failed')
    expect(mocks.refresh).not.toHaveBeenCalled(); expect(mocks.fetch).toHaveBeenCalledOnce()
  })
  it('bounds polling and reports unconfirmed completion without clearing or reloading rows', async () => {
    render(<PublishedRefreshControl />)
    await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Refresh' })) })
    await act(async () => { await vi.advanceTimersByTimeAsync(310_000) })
    expect(screen.getByRole('status')).toHaveTextContent('completion is not yet confirmed')
    expect(mocks.refresh).not.toHaveBeenCalled(); expect(mocks.fetch).toHaveBeenCalledOnce()
  })
  it('does not poll after unmount', async () => {
    const view = render(<PublishedRefreshControl />)
    await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Refresh' })) })
    view.unmount()
    await act(async () => { await vi.advanceTimersByTimeAsync(20_000) })
    expect(mocks.range).not.toHaveBeenCalled()
  })
  it.each(['success', 'no_change'] as const)('recovers receipt monitoring through the actual actions to matching %s without triggering again', async status => {
    mocks.range.mockRejectedValueOnce(new Error('fictional receipt read unavailable')).mockResolvedValueOnce([headers])
    render(<><p>Previously published fictional rows</p><PublishedRefreshControl /></>)
    const button = screen.getByRole('button', { name: 'Refresh' })
    await act(async () => { fireEvent.click(button) })
    const acceptedId = requestId()
    mocks.range.mockResolvedValueOnce([headers, [acceptedId, status, 'fictional-v2', '2026-11-19T01:00:00Z']])
    await act(async () => { await vi.advanceTimersByTimeAsync(10_000) })
    expect(screen.getByText('Previously published fictional rows')).toBeVisible()
    expect(button).toBeDisabled()
    expect(screen.getByRole('status')).toHaveTextContent('may still be running')
    expect(mocks.refresh).not.toHaveBeenCalled()
    await act(async () => { fireEvent.click(button); await vi.advanceTimersByTimeAsync(10_000) })
    expect(button).toBeDisabled()
    expect(screen.getByRole('status')).toHaveTextContent("Waiting for Kanban's completion receipt")
    expect(mocks.refresh).not.toHaveBeenCalled()
    await act(async () => { await vi.advanceTimersByTimeAsync(10_000) })
    expect(mocks.fetch).toHaveBeenCalledOnce()
    expect(requestId()).toBe(acceptedId)
    expect(mocks.range).toHaveBeenCalledTimes(3)
    expect(mocks.refresh).toHaveBeenCalledOnce()
    expect(button).not.toBeDisabled()
    expect(screen.getByRole('status')).toHaveTextContent(status === 'success' ? 'finished' : 'no changes')
  })
  it('recovers an interrupted status action without releasing the guard or starting a second bot run', async () => {
    render(<PublishedRefreshControl />)
    const button = screen.getByRole('button', { name: 'Refresh' })
    await act(async () => { fireEvent.click(button) })
    const acceptedId = requestId()
    mocks.auth.mockRejectedValueOnce(new Error('fictional private action interruption'))
    await act(async () => { await vi.advanceTimersByTimeAsync(10_000) })
    expect(button).toBeDisabled()
    expect(mocks.refresh).not.toHaveBeenCalled()
    expect(screen.getByRole('status')).not.toHaveTextContent('private action interruption')
    mocks.range.mockResolvedValueOnce([headers, [acceptedId, 'success', 'fictional-v2', '2026-11-19T01:00:00Z']])
    await act(async () => { await vi.advanceTimersByTimeAsync(10_000) })
    expect(mocks.fetch).toHaveBeenCalledOnce()
    expect(mocks.refresh).toHaveBeenCalledOnce()
    expect(button).not.toBeDisabled()
  })
  it('keeps unconfirmed monitoring bounded by the original five-minute window', async () => {
    mocks.range.mockRejectedValue(new Error('fictional completion read outage'))
    render(<PublishedRefreshControl />)
    const button = screen.getByRole('button', { name: 'Refresh' })
    await act(async () => { fireEvent.click(button) })
    await act(async () => { await vi.advanceTimersByTimeAsync(290_000) })
    expect(button).toBeDisabled()
    expect(screen.getByRole('status')).toHaveTextContent('may still be running')
    await act(async () => { await vi.advanceTimersByTimeAsync(20_000) })
    expect(button).not.toBeDisabled()
    expect(screen.getByRole('status')).toHaveTextContent('completion is not yet confirmed')
    expect(mocks.fetch).toHaveBeenCalledOnce()
    expect(mocks.refresh).not.toHaveBeenCalled()
    expect(mocks.range).toHaveBeenCalledTimes(30)
  })
})
